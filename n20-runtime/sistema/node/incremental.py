"""Incremental BF16 experimental output transforms; never an answer generator."""
from __future__ import annotations

from decimal import Decimal, localcontext
from math import isfinite
from random import Random

from ..core.answer import Answer
from ..core.topology import node_sort_key


def _numeric(value: object) -> Decimal | None:
    # Do not coerce bool, text, NaN, infinity or a number outside numeric protocol range.
    if type(value) not in (int, float):
        return None
    try:
        if not isfinite(value):
            return None
    except OverflowError:
        return None
    return Decimal(str(value))


def _delta(base: Decimal, sign: int) -> Answer | None:
    with localcontext() as ctx:
        ctx.prec = max(28, len(base.as_tuple().digits) + 4)
        answer = base + abs(base) * Decimal("0.2") * sign
    # 0 remains 0. A value outside the protocol's finite range is an abstention.
    if not isfinite(float(answer)):
        return None
    return int(answer) if answer == answer.to_integral_value() else float(answer)


async def transform(*, node_id: str, own_answer: Answer | None, colluders, collusion: bool,
                    seed: int, round_index: int, read_peer):
    """Return submitted numeric value and base node (empty for no numeric base).

    All nodes are pre-generated by the incremental coordinator. A peer read
    must use only the same run/round. A transport failure is not a nonnumeric
    answer and propagates, so participants cannot silently choose different bases.
    """
    if not collusion:
        base = _numeric(own_answer)
        if base is None:
            return None, ""
        sign = 1 if Random(f"{seed}:{round_index}:{node_id}:incremental-independent").getrandbits(1) else -1
        return _delta(base, sign), node_id

    cohort = sorted(colluders, key=node_sort_key)
    if not cohort or node_id not in cohort or len(set(cohort)) != len(cohort):
        raise ValueError("Invalid incremental collusion cohort")
    for base_id in cohort:
        value = own_answer if base_id == node_id else await read_peer(base_id)
        base = _numeric(value)
        if base is not None:
            return _delta(base, +1), base_id
    # Not an intentional omission: the selected cohort produced no finite number.
    return None, ""
